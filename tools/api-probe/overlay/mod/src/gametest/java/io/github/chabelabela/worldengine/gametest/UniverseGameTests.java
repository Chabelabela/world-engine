package io.github.chabelabela.worldengine.gametest;

import io.github.chabelabela.worldengine.level.PlanetTerrain;
import io.github.chabelabela.worldengine.level.UniverseChunkGenerator;
import io.github.chabelabela.worldengine.nativebridge.PlanetKind;
import io.github.chabelabela.worldengine.nativebridge.TerrainColumns;
import io.github.chabelabela.worldengine.planet.BiomeTable;
import io.github.chabelabela.worldengine.planet.LevelShape;
import io.github.chabelabela.worldengine.planet.PlanetHit;
import io.github.chabelabela.worldengine.planet.Planets;
import net.fabricmc.fabric.api.gametest.v1.GameTest;
import net.minecraft.core.BlockPos;
import net.minecraft.core.Holder;
import net.minecraft.core.QuartPos;
import net.minecraft.core.registries.Registries;
import net.minecraft.gametest.framework.GameTestHelper;
import net.minecraft.network.chat.Component;
import net.minecraft.resources.Identifier;
import net.minecraft.resources.ResourceKey;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.tags.FluidTags;
import net.minecraft.world.level.ChunkPos;
import net.minecraft.world.level.Level;
import net.minecraft.world.level.biome.Biome;
import net.minecraft.world.level.block.Blocks;
import net.minecraft.world.level.levelgen.Heightmap;

/**
 * World generation checks in a real server. The GameTest world gets an extra dimension,
 * {@code worldengine:gametest_universe}, generated by {@link UniverseChunkGenerator} (see this source set's
 * data pack); each test generates chunks there and compares them with the native core.
 */
public class UniverseGameTests {
    private static final ResourceKey<Level> UNIVERSE =
            ResourceKey.create(Registries.DIMENSION, Identifier.fromNamespaceAndPath("worldengine", "gametest_universe"));
    /** Columns on the home planet (several faces) and on the moon. */
    private static final int[][] COLUMNS = {{3, 5}, {1_234, -4_321}, {-7_000, 6_000}, {9_000, -9_000}, {106_100, 40}};

    @GameTest
    public void chunksFollowTheCore(GameTestHelper helper) {
        ServerLevel level = universe(helper);
        for (int[] c : COLUMNS) {
            PlanetHit hit = Planets.at(c[0], c[1]);
            int height = PlanetTerrain.column(hit, level.getSeed()).height(0, 0);
            level.getChunk(c[0] >> 4, c[1] >> 4); // generates the chunk fully
            String where = hit.planet().name() + " (" + c[0] + ", " + c[1] + ") at " + height + " m";
            check(helper, level.getBlockState(new BlockPos(c[0], LevelShape.MIN_Y, c[1])).is(Blocks.BEDROCK),
                    "bedrock floor at " + where);
            // Decoration may change the top block (a tree turns grass into dirt) but never removes it.
            check(helper, !level.getBlockState(new BlockPos(c[0], LevelShape.surfaceY(height), c[1])).isAir(),
                    "solid surface at " + where);
            boolean wet = level.getFluidState(new BlockPos(c[0], LevelShape.SEA_LEVEL - 1, c[1])).is(FluidTags.WATER);
            boolean ocean = height < 0 && hit.planet().kind() == PlanetKind.TERRESTRIAL;
            check(helper, wet == ocean, "water at sea level iff ocean, at " + where);
        }
        helper.succeed();
    }

    @GameTest
    public void spaceIsEmpty(GameTestHelper helper) {
        ServerLevel level = universe(helper);
        int x = 70_000;
        int z = 0;
        check(helper, Planets.at(x, z) == null, "test column must be off every planet");
        level.getChunk(x >> 4, z >> 4);
        check(helper, level.getHeight(Heightmap.Types.WORLD_SURFACE, x, z) == level.getMinY(), "no blocks in space");
        check(helper, level.getNoiseBiome(QuartPos.fromBlock(x), 0, QuartPos.fromBlock(z)).is(biome(BiomeTable.VOID)),
                "space is the void biome");
        helper.succeed();
    }

    @GameTest
    public void biomesFollowTheTable(GameTestHelper helper) {
        ServerLevel level = universe(helper);
        UniverseChunkGenerator generator = (UniverseChunkGenerator) level.getChunkSource().getGenerator();
        for (int[] c : COLUMNS) {
            int qx = QuartPos.fromBlock(c[0]);
            int qz = QuartPos.fromBlock(c[1]);
            int sampleX = QuartPos.toBlock(qx) + 2;
            int sampleZ = QuartPos.toBlock(qz) + 2;
            PlanetHit hit = Planets.at(sampleX, sampleZ);
            TerrainColumns column = PlanetTerrain.column(hit, level.getSeed());
            String expected = BiomeTable.biomeId(column.biome(0, 0));
            level.getChunk(c[0] >> 4, c[1] >> 4);
            Holder<Biome> stored = level.getNoiseBiome(qx, QuartPos.fromBlock(64), qz);
            check(helper, stored.is(biome(expected)), "chunk biome at (" + c[0] + ", " + c[1] + ") is " + expected);
            Holder<Biome> direct = generator.getBiomeSource()
                    .createUncachedResolver(level.getChunkSource().randomState())
                    .getNoiseBiome(qx, QuartPos.fromBlock(64), qz);
            check(helper, direct.is(biome(expected)), "biome source at (" + c[0] + ", " + c[1] + ") is " + expected);
        }
        helper.succeed();
    }

    @GameTest
    public void spawnIsOnDryLand(GameTestHelper helper) {
        ServerLevel level = universe(helper);
        ChunkPos origin = level.getChunkSource().getGenerator().getOrigin(level.getChunkSource().randomState());
        PlanetHit hit = Planets.at(origin.getMinBlockX() + 8, origin.getMinBlockZ() + 8);
        check(helper, hit != null && hit.planet() == Planets.HOME, "spawn chunk is on the home planet");
        int height = PlanetTerrain.column(hit, level.getSeed()).height(0, 0);
        check(helper, height >= 1, "spawn column is dry land, got " + height + " m");
        helper.succeed();
    }

    private static ServerLevel universe(GameTestHelper helper) {
        ServerLevel level = helper.getLevel().getServer().getLevel(UNIVERSE);
        check(helper, level != null, "the gametest_universe dimension exists");
        return level;
    }

    private static ResourceKey<Biome> biome(String id) {
        return ResourceKey.create(Registries.BIOME, Identifier.parse(id));
    }

    private static void check(GameTestHelper helper, boolean condition, String what) {
        helper.assertTrue(condition, Component.literal(what));
    }
}
